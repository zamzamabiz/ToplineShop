export type Status =
  | "PLANNED"
  | "READY"
  | "IN_PROGRESS"
  | "BLOCKED"
  | "PARTIAL"
  | "PASS"
  | "CLOSED"
  | "DEFERRED"
  | "NOT_STARTED"
  | "ACTIVE"
  | "ENFORCED";

export interface Phase {
  id: string;
  number: number;
  name: string;
  objective: string;
  status: Status;
  progress: number;
  megaPromptTarget: number;
  megaPromptsCompleted: number;
  dependencies: string[];
  frontendGate: Status;
  backendGate: Status;
  databaseGate: Status;
  testingGate: Status;
  ownerApproval: Status;
  currentTask: string | null;
  taskCount: number;
  completedTaskCount: number;
}

export interface Task {
  id: string;
  phase: string;
  title: string;
  objective: string;
  status: Status;
  priority: "HIGH" | "MEDIUM" | "LOW";
  dependencies: string[];
  startedAt: string | null;
  completedAt: string | null;
  wdrPath: string | null;
  commitHash: string | null;
  tests: Status;
  build: Status;
  ownerApproval: Status;
  pmApproval: Status;
  notes: string;
}

export interface Module {
  id: string;
  name: string;
  description: string;
  status: Status;
  phase: string;
}

export interface ArchitectureItem {
  id: string;
  layer: string;
  technology: string;
  status: Status;
  notes: string;
}

export interface QualityGate {
  id: string;
  name: string;
  description: string;
  status: Status;
  enforcedBy: string;
}

export interface Risk {
  id: string;
  title: string;
  description: string;
  severity: "LOW" | "MEDIUM" | "HIGH" | "CRITICAL";
  status: Status;
  mitigation: string;
}

export interface Decision {
  id: string;
  title: string;
  description: string;
  decidedBy: string;
  date: string;
  status: Status;
}

export interface WdrEntry {
  id: string;
  taskId: string;
  phase: string;
  status: Status;
  date: string;
  commitHash: string | null;
  pmAudit: Status;
}

export interface ProjectRegistry {
  project: string;
  version: string;
  status: Status;
  developmentPolicy: string;
  protocol: string;
  currentPhase: string;
  currentTask: string | null;
  lastCompletedTask: string | null;
  nextPlannedTask: string;
  overallCompletion: number;
  lastUpdated: string;
  phases: Phase[];
  tasks: Task[];
  modules: Module[];
  architecture: ArchitectureItem[];
  technology: {
    frontend: string[];
    backend: string[];
    database: string[];
    infrastructure: string[];
  };
  qualityGates: QualityGate[];
  risks: Risk[];
  decisions: Decision[];
  approvals: { owner: Status; pm: Status };
  wdrs: WdrEntry[];
  git: { initialized: boolean; lastCommit: string | null };
  github: { configured: boolean; url: string | null; pushAllowed: boolean };
  build: { lastResult: Status; lastRun: string | null };
  tests: { lastResult: Status; lastRun: string | null };
  deployment: { environment: string; status: Status }[];
}

