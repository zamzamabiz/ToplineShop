/**
 * Resolves a raw country string to an ISO 3166-1 alpha-2 code.
 * Returns undefined if no mapping found (no fuzzy guessing).
 */
export function resolveCountryCode(raw: string): string | undefined {
  if (!raw) return undefined;
  const trimmed = raw.trim();
  if (COUNTRY_ALIASES[trimmed] !== undefined) return COUNTRY_ALIASES[trimmed];
  const upper = trimmed.toUpperCase();
  if (COUNTRY_ALIASES[upper] !== undefined) return COUNTRY_ALIASES[upper];
  return undefined;
}
